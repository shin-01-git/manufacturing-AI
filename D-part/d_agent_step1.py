import streamlit as st       # 대시보드(웹 화면)를 만드는 도구
import pandas as pd          # 표 데이터(csv)를 다루는 도구

# ---- 1. 설정값 (요금/탄소 환산 계수) -----------------------
# ground_truth 분석에서 확인된 관계
요금_단가 = 180        # 전력량 × 180 = 요금(원)
탄소_계수 = 0.424      # 전력량 × 0.424 = 탄소배출량

# 검증 파일 경로 (가볍고 숫자 확인용). 원본은 읽기만 한다.
GT_경로 = r"C:\Users\82104\Desktop\DONG-EUI UNIVERSITY\may-dataset\rtu_ground_truth_may.csv"


# ---- 2. 데이터 불러오기 (한 번만 읽고 저장해둠 = 캐싱) ------
@st.cache_data   # 이 줄이 "한 번 읽은 건 저장해둬" 라는 뜻 -> 화면이 빨라짐
def 데이터_불러오기():
    df = pd.read_csv(GT_경로)
    df["id"] = pd.to_datetime(df["id"])   # 글자로 된 시간을 날짜형으로 변환
    return df


# ---- 3. 화면 그리기 ----------------------------------------
st.title("공장 에너지 맞춤 대시보드 (D 1단계)")

df = 데이터_불러오기()

# 사용자가 역할을 고르는 드롭다운
역할 = st.selectbox(
    "당신의 역할을 선택하세요",
    ["설비 관리 담당자", "에너지 관리 담당자"]
)

st.write(f"선택한 역할: **{역할}**")
st.divider()   # 가로 구분선

# ---- 4. 역할에 따라 다른 정보 보여주기 (핵심: 필터링) -------
if 역할 == "설비 관리 담당자":
    st.subheader("⚙️ 설비 관점 정보")
    st.write("시간별 전력 사용량을 확인합니다. (정상/주의/이상 판단의 기초)")
    # 설비 담당은 '전력' 중심 -> hourly_pow 를 보여줌
    st.line_chart(df.set_index("id")["hourly_pow"])
    st.caption("hourly_pow = 시간별 전력 사용량")

elif 역할 == "에너지 관리 담당자":
    st.subheader("🌱 에너지/탄소 관점 정보")
    st.write("전력량을 요금과 탄소로 환산해 보여줍니다.")

    # 전력량으로부터 요금/탄소를 직접 '계산'한다 (숫자는 코드가 만든다!)
    총_전력 = df["hourly_pow"].sum()
    예상_요금 = 총_전력 * 요금_단가
    예상_탄소 = 총_전력 * 탄소_계수

    # 숫자 3개를 큰 카드로 표시
    열1, 열2, 열3 = st.columns(3)
    열1.metric("총 전력량", f"{총_전력:,.0f}")
    열2.metric("예상 요금(원)", f"{예상_요금:,.0f}")
    열3.metric("예상 탄소", f"{예상_탄소:,.0f}")

    st.caption("요금 = 전력량 × 180,  탄소 = 전력량 × 0.424")
